export interface Product {
    imgSrc: string;
    title: string;
    slug: string;
    weight: string;
    rating: number;
    price: number;
    description: string;
}

export interface ProductWithCategory extends Product {
    category: string;
    categoryName: string;
}

export function findProductBySlug(slug: string): ProductWithCategory | null {
    const data = products[0];

    for (const categoryKey in data) {
        const categoryArray = data[categoryKey as keyof typeof data];
        if (Array.isArray(categoryArray) && categoryArray.length > 0) {
            const category = categoryArray[0];
            const categoryName = category?.name || categoryKey;
            for (const subCategoryKey in category) {
                if (subCategoryKey === 'name') continue;
                const items = category[subCategoryKey as keyof typeof category];
                if (Array.isArray(items)) {
                    const found = items.find((item: Product) => item.slug === slug);
                    if (found) return { ...found, category: categoryKey, categoryName };
                }
            }
        }
    }

    return null;
}